function formatMetadata(raw) {
  const meta = (raw || "").trim();
  if (!meta) return "";
  const inner = meta.startsWith("(") && meta.endsWith(")") ? meta.slice(1, -1).trim() : meta;
  return inner ? ` (${inner})` : "";
}
