function findMetadataSpan(line, from = 0) {
  let i = from;
  while (i < line.length && line[i] === " ") i++;
  if (line[i] !== "(") return null;
  let depth = 0;
  for (let j = i; j < line.length; j++) {
    if (line[j] === "(") depth++;
    else if (line[j] === ")") {
      depth--;
      if (depth === 0) {
        return { start: i, end: j, content: line.slice(i + 1, j) };
      }
    }
  }
  return null;
}

